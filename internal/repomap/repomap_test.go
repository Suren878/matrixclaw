func defNames(tags fileTags) []string {
	var names []string
	for _, def := range tags.defs {
		names = append(names, def.name)
	}
	return names
}

func TestGoDefinitions(t *testing.T) {
	src := `package server

import (
	"context"
	"strings"

	"example.com/app/store"
)

const Version = "1"

var (
	defaultPort = 8080
	_           = strings.TrimSpace
)

type Handler interface {
	Serve(ctx context.Context) error
}

type Server struct{ store *store.Store }

func (s *Server) Start(
	ctx context.Context,
	port int,
) error {
	local := defaultPort
	_ = local
	return s.store.Open(ctx, strings.TrimSpace(Version))
}

func New() *Server { return &Server{} }
`
	tags := extract("server.go", []byte(src))
	want := []string{"Version", "defaultPort", "Handler", "Serve", "Server", "Start", "New"}
	if got := defNames(tags); !slices.Equal(got, want) {
		t.Fatalf("defs = %v, want %v", got, want)
	}
	start := tags.defs[5]
	if start.line != 23 || start.text != "func (s *Server) Start( ctx context.Context, port int, ) error" {
		t.Errorf("Start = %d %q", start.line, start.text)
	}
	if serve := tags.defs[3]; serve.text != "\tServe(ctx context.Context) error" || serve.indent != 1 {
		t.Errorf("Serve = %q", serve.text)
	}
	for _, name := range []string{"Open", "Store", "store", "defaultPort", "Version", "Server"} {
		if tags.refs[name] == 0 {
			t.Errorf("no reference to %s in %v", name, tags.refs)
		}
	}
	for _, name := range []string{"local", "ctx", "port", "TrimSpace", "strings", "context", "error", "len"} {
		if tags.refs[name] != 0 {
			t.Errorf("%s counted as a reference: %v", name, tags.refs)
		}
	}
	generated := extract("gen.go", []byte("// Code generated by stringer. DO NOT EDIT.\n\npackage server\n\nfunc X() {}\n"))
	if len(generated.defs) != 0 {
		t.Errorf("generated file defs = %v", defNames(generated))
	}
}

func TestLexedDefinitions(t *testing.T) {
	cases := []struct {
		file, src string
		want      []string
	}{
		{"shapes.py", "class Circle(Base):\n    def area(self):\n        return compute_area(self.r)\n\ndef compute_area(r):\n    return r\n",
			[]string{"Circle", "area", "compute_area"}},
		{"shapes.ts", "import { type Base } from './base';\nexport interface Shape { area(): number }\nexport type Id = string;\n" +
			"export class Circle implements Shape {\n  constructor(r: number) { this.r = r; }\n  area(): number {\n    return computeArea(this.r);\n  }\n}\n" +
			"export function computeArea(r: number): number { return r; }\nexport function reset() {\n}\nexport const handler = async () => {\n  const local = 1;\n  useEffect(() => {\n  });\n};\n",
			[]string{"Shape", "Id", "Circle", "area", "computeArea", "reset", "handler"}},
		{"shapes.rs", "pub struct Circle { r: f64 }\npub trait Shape { fn area(&self) -> f64; }\nimpl Shape for Circle {\n    fn area(&self) -> f64 { compute_area(self.r) }\n}\npub fn compute_area(r: f64) -> f64 { r }\n",
			[]string{"Circle", "Shape", "area", "area", "compute_area"}},
		{"Circle.java", "public class Circle extends Base {\n    public Circle(double r) { this.r = r; }\n    public double area() { return computeArea(r); }\n    static double computeArea(double r) { return r; }\n}\n",
			[]string{"Circle", "Circle", "area", "computeArea"}},
		{"shapes.cpp", "class Circle : public Shape {\n  double area() const override { return compute_area(r_); }\n};\ndouble Circle::perimeter() const { return 2 * r_; }\n",
			[]string{"Circle", "area", "perimeter"}},
		{"shapes.c", "struct circle { double r; };\nstatic double compute_area(double r) { return r; }\nint main(void) { struct circle c; printf(\"%f\", compute_area(c.r)); return 0; }\n",
			[]string{"circle", "compute_area", "main"}},
	}
	for _, tc := range cases {
		t.Run(tc.file, func(t *testing.T) {
			tags := extract(tc.file, []byte(tc.src))
			if got := defNames(tags); !slices.Equal(got, tc.want) {
				t.Errorf("defs = %v, want %v", got, tc.want)
			}
			if tags.refs["compute_area"]+tags.refs["computeArea"] == 0 {
				t.Errorf("call not counted as a reference: %v", tags.refs)
			}
		})
	}
}

// writeFiles writes path → content pairs below dir and lists them as Files.
func writeFiles(t *testing.T, dir string, pairs ...string) []File {
	t.Helper()
	var files []File
	for i := 0; i+1 < len(pairs); i += 2 {
		path := filepath.Join(dir, filepath.FromSlash(pairs[i]))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(pairs[i+1]), 0o644); err != nil {
			t.Fatal(err)
		}
		info, err := os.Stat(path)
		if err != nil {
			t.Fatal(err)
		}
		files = append(files, File{Path: pairs[i], Size: info.Size(), ModTime: info.ModTime()})
	}
	return files
}

// mapFiles lists the files of a map in its order.
func mapFiles(text string) []string {
	var files []string
	for line := range strings.SplitSeq(text, "\n") {
		if name, ok := strings.CutSuffix(line, ":"); ok && !strings.Contains(line, "│") {
			files = append(files, name)
		}
	}
	return files
}

func TestRankingPrefersReferencedAndFocusedDefinitions(t *testing.T) {
	dir := t.TempDir()
	files := writeFiles(t, dir,
		"core/store.go", "package core\n\ntype Store struct{}\n\nfunc OpenStore() *Store { return &Store{} }\n",
		"core/cache.go", "package core\n\ntype CacheEntry struct{}\n\nfunc NewCacheEntry() CacheEntry { return CacheEntry{} }\n",
		"app/a.go", "package app\n\nimport \"x.io/core\"\n\nfunc A() { core.OpenStore(); core.OpenStore() }\n",
		"app/b.go", "package app\n\nimport \"x.io/core\"\n\nfunc B() *core.Store { return core.OpenStore() }\n",
		"app/c.go", "package app\n\nimport \"x.io/core\"\n\nfunc C() { core.NewCacheEntry() }\n",
	)
	var mapper Mapper
	overview, err := mapper.Map(context.Background(), Request{Root: dir, Files: files})
	if err != nil {
		t.Fatal(err)
	}
	if got := mapFiles(overview.Text); len(got) == 0 || got[0] != "core/store.go" {
		t.Fatalf("overview files = %v\n%s", got, overview.Text)
	}
	focused, err := mapper.Map(context.Background(), Request{Root: dir, Files: files, FocusFiles: []string{"app/c.go"}})
	if err != nil {
		t.Fatal(err)
	}
	got := mapFiles(focused.Text)
	if len(got) == 0 || got[0] != "core/cache.go" || slices.Contains(got, "app/c.go") {
		t.Fatalf("focused files = %v\n%s", got, focused.Text)
	}
	symbol, err := mapper.Map(context.Background(), Request{Root: dir, Files: files[:2], FocusSymbols: []string{"NewCacheEntry"}})
	if err != nil {
		t.Fatal(err)
	}
	if got := mapFiles(symbol.Text); len(got) == 0 || got[0] != "core/cache.go" {
		t.Fatalf("files for a focus symbol = %v\n%s", got, symbol.Text)
	}
}

func TestMapFitsTheBudget(t *testing.T) {
	dir := t.TempDir()
	var pairs []string
	for i := range 300 {
		pairs = append(pairs, fmt.Sprintf("pkg/file%03d.go", i),
			fmt.Sprintf("package pkg\n\nfunc HandleRequestNumber%03d(ctx Context, input string) (string, error) {\n\treturn HandleRequestNumber%03d(ctx, input)\n}\n", i, (i+1)%300))
	}
	files := writeFiles(t, dir, pairs...)
	var mapper Mapper
	for _, budget := range []int{1024, 4096} {
		drawn, err := mapper.Map(context.Background(), Request{Root: dir, Files: files, Tokens: budget})
		if err != nil {
			t.Fatal(err)
		}
		if drawn.Tokens > budget*115/100 || drawn.Tokens < budget/2 || drawn.Shown == 0 || drawn.Mapped != 300 {
			t.Errorf("budget %d: tokens %d, shown %d of %d", budget, drawn.Tokens, drawn.Shown, drawn.Mapped)
		}
	}
}

func TestMapReadsChangedFilesAgain(t *testing.T) {
	dir := t.TempDir()
	files := writeFiles(t, dir, "a.py", "def first_function():\n    pass\n")
	var mapper Mapper
	if drawn, _ := mapper.Map(context.Background(), Request{Root: dir, Files: files}); !strings.Contains(drawn.Text, "first_function") {
		t.Fatalf("map = %q", drawn.Text)
	}
	files = writeFiles(t, dir, "a.py", "def second_function():\n    pass\n\n")
	files[0].ModTime = files[0].ModTime.Add(time.Second)
	if drawn, _ := mapper.Map(context.Background(), Request{Root: dir, Files: files}); !strings.Contains(drawn.Text, "second_function") || strings.Contains(drawn.Text, "first_function") {
		t.Fatalf("map after a change = %q", drawn.Text)
	}
}
